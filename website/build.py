"""Build the static VoltSafe website from the shared course content.

    python website/build.py

Writes website/content.js (courses, roles and substation areas taken from
safety_app/content.py) and website/index.html (page.html wrapped in a full
HTML document) so the static site and the Flask app never drift apart.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from safety_app.content import AREAS, PASS_MARK, ROLES, TRACKS  # noqa: E402

data = {"ROLES": ROLES, "TRACKS": TRACKS, "AREAS": AREAS, "PASS_MARK": PASS_MARK}
(HERE / "content.js").write_text(
    "// Generated by website/build.py from safety_app/content.py - do not edit.\n"
    "window.VOLTSAFE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)

page = (HERE / "page.html").read_text(encoding="utf-8")
head, _, body = page.partition("<!--/head-->")
(HERE / "index.html").write_text(
    "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
    "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
    + head.strip() + "\n</head>\n<body>\n" + body.strip() + "\n</body>\n</html>\n",
    encoding="utf-8",
)
print("Built website/content.js and website/index.html")
